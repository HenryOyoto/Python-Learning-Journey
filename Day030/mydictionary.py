# Dictionary
# Using loops in dictionary

explanations = {
    "Henry": "Henry is a human being and an engineer",
    "Cow": "Cow is an animal that gives milk and dairy",
    "Hospital": "Hospital is where you get treatment when sick",
    "Bash": "Bash is a slang used to refer to birthday party"}

for explanation in explanations:
    print(explanation, explanations[explanation], sep=": ")


